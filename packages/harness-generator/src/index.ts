function smtCheckerInput(sourcePath: string) {
  return `${JSON.stringify(
    {
      language: "Solidity",
      sources: {
        [sourcePath]: {
          urls: [sourcePath]
        }
      },
      settings: {
        modelChecker: {
          engine: "chc",
          invariants: ["contract", "reentrancy"],
          showUnproved: true,
          targets: ["assert", "balance", "divByZero", "overflow", "underflow"]
        },
        outputSelection: {
          "*": {
            "*": ["abi"],
            "": ["ast"]
          }
        }
      }
    },
    null,
    2
  )}\n`;
}

function scribbleAnnotations(contractName: string, sourcePath: string, properties: Property[]) {
  const templates = properties.map(
    (property) => `### ${property.id}

Intent: ${singleLine(property.text)}

Risk: ${property.risk}

\`\`\`solidity
/// #invariant {:msg "ProofBoard ${escapeScribbleMessage(property.id)}"} <BOOLEAN_EXPRESSION>;
\`\`\`
`
  );

  return `# ProofBoard Scribble Annotation Worksheet

Target contract: \`${contractName}\`

Target source: \`${sourcePath}\`

This file is a review scaffold, not an instrumented contract and not verification evidence. ProofBoard does not translate natural-language intent into executable Solidity expressions automatically because a guessed or \`true\` expression would create misleading, potentially vacuous checks.

For each approved property:

1. Replace \`<BOOLEAN_EXPRESSION>\` with a contract-specific Solidity expression.
2. Place the completed annotation immediately before the relevant contract or function in \`${sourcePath}\`.
3. Review assumptions, quantification, old-state references, and arithmetic behavior.
4. Instrument the reviewed source with Scribble and run the resulting tests.
5. Preserve raw instrumentation and test output before recording evidence in ProofBoard.

## Property Templates

${templates.join("\n") || "No properties were selected. Add human-approved properties before creating annotations.\n"}
`;
}

function singleLine(value: string) {
  return value.replace(/\s+/g, " ").trim();
}

function escapeScribbleMessage(value: string) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function certoraConfiguration(contractName: string, sourcePath: string) {
  return `${JSON.stringify(
    {
      files: [sourcePath],
      verify: `${contractName}:verification/certora/Proofboard.spec`,
      msg: `ProofBoard scaffold for ${contractName}`
    },
    null,
    2
  )}\n`;
}

function certoraSpecification(contractName: string, sourcePath: string, properties: Property[]) {
  const templates = properties.map(
    (property) => `/*
ProofBoard property: ${safeComment(property.id)}
Intent: ${safeComment(singleLine(property.text))}
Risk: ${property.risk}

Review the target methods and replace <BOOLEAN_EXPRESSION> before removing this block comment.

rule pb_${verificationIdentifier(property)} {
    env e;
    assert <BOOLEAN_EXPRESSION>, "ProofBoard ${escapeCvlMessage(property.id)}";
}
*/
`
  );

  return `/*
ProofBoard Certora CVL worksheet
Target contract: ${safeComment(contractName)}
Target source: ${safeComment(sourcePath)}

This is an inactive specification scaffold, not verification evidence. It intentionally contains no active rules because ProofBoard cannot safely translate natural-language intent into contract-specific CVL expressions.
*/

${templates.join("\n") || "/* No properties were selected. Add human-approved properties before creating CVL rules. */\n"}
`;
}

function verificationIdentifier(property: Property) {
  const identifier = property.id.replace(/[^a-zA-Z0-9_]/g, "_");
  return /^[a-zA-Z_]/.test(identifier) ? identifier : `property_${identifier}`;
}

function safeComment(value: string) {
  return value.replace(/\*\//g, "* /");
}

function escapeCvlMessage(value: string) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function echidnaConfiguration() {
  return `testMode: property
testLimit: 50000
seqLen: 100
shrinkLimit: 5000
coverage: true
corpusDir: corpus-echidna
allContracts: false
`;
}

function echidnaProperties(contractName: string, sourcePath: string, properties: Property[]) {
  const templates = properties.map(
    (property) => `### ${property.id}

Intent: ${singleLine(property.text)}

Risk: ${property.risk}

\`\`\`solidity
function echidna_pb_${verificationIdentifier(property)}() public view returns (bool) {
    return <BOOLEAN_EXPRESSION>;
}
\`\`\`
`
  );

  return `# ProofBoard Echidna Property Worksheet

Target contract: \`${contractName}\`

Target source: \`${sourcePath}\`

This file is an inactive harness worksheet, not fuzzing evidence. Create a dedicated Echidna harness that deploys or inherits the reviewed target, exposes only intended state-changing actions, and then adds completed property functions from this file.

Before running Echidna:

1. Replace each \`<BOOLEAN_EXPRESSION>\` with a target-specific Solidity expression.
2. Define constructor state, actors, balances, token approvals, and privileged roles.
3. Bound or reject meaningless inputs without excluding security-relevant states.
4. Review whether the configured sequence length can reach the intended protocol states.
5. Preserve the seed, corpus, coverage, and raw failure sequence before recording evidence.

## Property Templates

${templates.join("\n") || "No properties were selected. Add human-approved properties before creating Echidna properties.\n"}
`;
}

function invariantName(property: Property) {
  const words = property.id
    .replace(/^property_/, "")
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean);

  const name = words
    .map((word, index) => (index === 0 ? word.toLowerCase() : word.charAt(0).toUpperCase() + word.slice(1)))
    .join("");

  return name || "generatedProperty";
}
